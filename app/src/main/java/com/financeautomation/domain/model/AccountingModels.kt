package com.financeautomation.domain.model

/**
 * Domain model representing a row in Table 1 (Debits) of a monthly ledger tab.
 * Pure Kotlin data class with zero Android framework dependencies.
 */
data class LedgerDebit(
    val tab: String,
    val row: Int,
    val uuid: String?,
    val dateSerial: Int?,
    val timeSerial: Double?,
    val account: String,
    val item: String,
    val tripTag: String?,
    val category: String,
    val total: Double,
    val companions: String,
    val myShare: Double,
    val owed: Double,
    val status: String
)

/**
 * Domain model representing a row in Table 3 (Payables) of a monthly ledger tab.
 * Pure Kotlin data class with zero Android framework dependencies.
 */
data class LedgerPayable(
    val tab: String,
    val row: Int,
    val uuid: String?,
    val dateIncurredSerial: Int?,
    val timeSerial: Double?,
    val paidBy: String,
    val whatFor: String,
    val amountOwed: Double,
    val dateRepaidSerial: Int?,
    val status: String
)

/**
 * Composite key identifying a physical cell's row location in a workbook.
 */
data class RowKey(
    val tab: String,
    val row: Int
)

/**
 * Represents a single cell update instruction in the workbook.
 */
data class CellEdit(
    val tab: String,
    val row: Int,
    val column: String,
    val value: Any?
)

/**
 * Target table classification in a monthly ledger tab.
 */
enum class TableType {
    DEBIT,
    INFLOW,
    PAYABLE
}

/**
 * Represents a new row append instruction targeting a specific table.
 */
data class NewRow(
    val table: TableType,
    val tab: String,
    val uuid: String,
    val cells: List<Any?>
)

/**
 * Details of debt settlement applied to a specific debit row.
 */
data class SettledRef(
    val tab: String,
    val row: Int,
    val uuid: String?,
    val applied: Double,
    val remaining: Double
)

/**
 * Complete, immutable execution plan generated by accounting use cases.
 * Stored in sync_queue.planJson before execution to guarantee idempotent two-phase application.
 */
data class AccountingPlan(
    val edits: List<CellEdit> = emptyList(),
    val appends: List<NewRow> = emptyList(),
    val settled: List<SettledRef> = emptyList(),
    val excess: Double = 0.0,
    val unmatched: Boolean = false,
    val message: String = ""
)

/**
 * Audit lineage record tracking debts and payables carried forward across monthly tabs.
 */
data class LineageRecord(
    val uuid: String,
    val carriedFromUuid: String,
    val rootUuid: String,
    val createdAt: Long
)

/**
 * Snapshot of ledger entries extracted from workbook tabs for waterfall and ranking processing.
 */
data class LedgerSnapshot(
    val debits: List<LedgerDebit> = emptyList(),
    val payables: List<LedgerPayable> = emptyList()
)

